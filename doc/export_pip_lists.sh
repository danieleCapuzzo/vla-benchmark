#!/usr/bin/env bash
# Esporta le pip list di ogni ambiente in file .md leggibili da Claude Code.
# Esegui questo script UNA VOLTA per ambiente, DOPO aver attivato il venv corretto.
#
# Uso:
#   source ~/Desktop/thesis-vla/.oft-env/bin/activate
#   bash export_pip_lists.sh oft-env
#
#   source ~/Desktop/thesis-vla/.mail-env/bin/activate
#   bash export_pip_lists.sh mail-env

set -e

ENV_NAME="${1:?Usage: bash export_pip_lists.sh <env-name>  (es. openvla-env | oft-env | mail-env)}"
OUT_DIR="pip-lists"
OUT_FILE="${OUT_DIR}/${ENV_NAME}.pip.md"

mkdir -p "$OUT_DIR"

{
    echo "# pip freeze — environment: ${ENV_NAME}"
    echo ""
    echo "> Automatically generated by export_pip_lists.sh. DO NOT overwrite by hand."
    echo "> Claude Code: read this file for package versions before writing code."
    echo ""
    echo "## Context"
    echo ""
    echo "- Export date: $(date -u '+%Y-%m-%d %H:%M UTC')"
    echo "- Python: $(python --version 2>&1)"
    echo "- Interpreter: $(which python)"
    PYCUDA=$(python -c "import torch; print(torch.__version__, torch.cuda.get_device_capability(0))" 2>/dev/null || echo "torch non importabile")
    echo "- torch / CUDA cap: ${PYCUDA}"
    echo ""
    echo "## Key packages (highlighted)"
    echo ""
    echo '```'
    pip freeze 2>/dev/null | grep -iE '^(torch|torchvision|torchaudio|transformers|tokenizers|timm|accelerate|bitsandbytes|tensorflow|tensorflow-metadata|numpy|diffusers|robosuite|bddl|robomimic|gymnasium|mamba-ssm|causal-conv1d|libero|dlimp|peft)([=@ ]|$)' || echo "(nessun match)"
    echo '```'
    echo ""
    echo "## pip freeze complete"
    echo ""
    echo '```'
    pip freeze 2>/dev/null
    echo '```'
} > "$OUT_FILE"

echo "Written to: $OUT_FILE"
